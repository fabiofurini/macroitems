"""LaTeX for table ``tab:forests`` and for the numbers quoted in its commentary,
generated from the CSV of ``forest_fixing.py``.

Usage::

    python experiments/forest_fixing_table.py experiments/results/forest_fixing.csv \\
        --rows experiments/results/tables/forest_fixing.tex \\
        --macros experiments/results/tables/forest_fixing_macros.tex

``--rows`` gets the nine body rows of the table, and ``--macros`` gets
``\\newcommand`` definitions for the ranges quoted in the text, for example
``\\ffZbestMin``.  Every generated number is wrapped in ``\\gen{...}``.  The
paper defines ``\\gen``, either as the identity or as a highlighting macro
during a revision, so the paper never contains a hand-copied number.
"""
from __future__ import annotations

import argparse
import csv
import math
import sys
from collections import Counter, defaultdict

ORIENTATIONS = ("in", "out", "mixed")
PROFITS = ("unc", "signs", "ties")


def rows_from(path):
    with open(path) as f:
        header = [line.strip() for line in f if line.startswith("#")]
    with open(path) as f:
        return header, list(csv.DictReader(line for line in f if not line.startswith("#")))


def half_up(x: float) -> int:
    return int(math.floor(x + 0.5))


def summarize(rows):
    by = defaultdict(list)
    discarded = Counter()
    for r in rows:
        if r["status"] == "ok":
            by[(r["orient"], r["profits"])].append(r)
        else:
            discarded[(r["orient"], r["profits"], r["status"])] += 1
    out = []
    for o in ORIENTATIONS:
        for p in PROFITS:
            R = by.get((o, p), [])
            if not R:
                continue
            N = len(R)
            mean = lambda k: sum(float(r[k]) for r in R) / N
            tot = lambda k: sum(int(r[k]) for r in R)
            Z, F = tot("Z"), tot("F")
            out.append(dict(
                orient=o, profits=p, N=N,
                gap_lp=mean("gap_lp_pct"), gap_heur=mean("gap_heur_pct"),
                Zs=100 * tot("fix_Z_solver") / Z, Zb=100 * tot("fix_Z_best") / Z,
                Fs=100 * tot("fix_F_solver") / F, Fb=100 * tot("fix_F_best") / F,
                multi=100 * sum(int(r["k0"]) > 1 for r in R) / N,
                nocrit=100 * sum(r["critical"] == "0" for r in R) / N))
    return out, discarded


def latex_rows(summary):
    g = lambda x: "\\gen{" + x + "}"
    lines = []
    for s in summary:
        cells = [f"{s['gap_lp']:.2f}", f"{s['gap_heur']:.2f}", f"{s['Zs']:.1f}", f"{s['Zb']:.1f}",
                 f"{s['Fs']:.1f}", f"{s['Fb']:.1f}", f"{s['multi']:.0f}", f"{s['nocrit']:.0f}"]
        lines.append(f"{s['orient']:5s} & {s['profits']:5s} & " + " & ".join(g(c) for c in cells)
                     + f"\\\\  % N={s['N']}")
    return lines


def latex_macros(summary):
    def rng(key):
        vals = [s[key] for s in summary]
        return half_up(min(vals)), half_up(max(vals))
    names = {"Zb": "ffZbest", "Zs": "ffZsolver", "Fb": "ffFbest", "Fs": "ffFsolver"}
    lines = []
    for key, name in names.items():
        lo, hi = rng(key)
        lines.append(f"\\newcommand{{\\{name}Min}}{{\\gen{{{lo}}}}}")
        lines.append(f"\\newcommand{{\\{name}Max}}{{\\gen{{{hi}}}}}")
    lines.append(f"\\newcommand{{\\ffInstances}}{{\\gen{{{min(s['N'] for s in summary)}}}}}")
    return lines


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--rows", help="output file for the table body")
    ap.add_argument("--macros", help="output file for the macros quoted in the text")
    ap.add_argument("--out", help="alias of --rows")
    a = ap.parse_args(argv)
    header, rows = rows_from(a.csv)
    summary, discarded = summarize(rows)
    stamp = ["% generated by experiments/forest_fixing_table.py from " + a.csv + " -- do not edit"]
    stamp += ["% " + h.lstrip("# ") for h in header]
    body = "\n".join(stamp + latex_rows(summary)) + "\n"
    macros = "\n".join(stamp + latex_macros(summary)) + "\n"
    rows_out = a.rows or a.out
    if rows_out:
        open(rows_out, "w").write(body)
    if a.macros:
        open(a.macros, "w").write(macros)
    sys.stdout.write(body + macros)
    for (o, p, s), v in sorted(discarded.items()):
        print(f"% discarded {o}:{p} {s}: {v}", file=sys.stderr)


if __name__ == "__main__":
    main()
