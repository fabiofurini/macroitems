"""LaTeX for the table on the literature benchmark, and for the numbers quoted in
its commentary, generated from the CSV of ``literature_fixing.py``.

Usage::

    python experiments/literature_fixing_table.py experiments/results/literature_fixing.csv \\
        --rows experiments/results/tables/literature_fixing.tex \\
        --macros experiments/results/tables/literature_fixing_macros.tex

Every number is wrapped in ``\\gen{...}``; see ``forest_fixing_table.py``.
"""
from __future__ import annotations

import argparse
import csv
import statistics
import sys

from forest_fixing_table import half_up


def load(path):
    with open(path) as f:
        header = [line.strip() for line in f if line.startswith("#")]
    with open(path) as f:
        return header, list(csv.DictReader(line for line in f if not line.startswith("#")))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--rows")
    ap.add_argument("--macros")
    a = ap.parse_args(argv)
    header, rows = load(a.csv)
    ok = [r for r in rows if r["status"] == "ok"]
    g = lambda x: "\\gen{" + x + "}"
    pct = lambda r, k: 100 * int(r[k]) / int(r["Z"]) if int(r["Z"]) else 0.0
    body = []
    for fam in ("telecom", "mining"):
        R = [r for r in ok if r["family"] == fam]
        if body and R:
            body.append("\\midrule")
        for r in R:
            name = r["name"].split("_")[0]
            star = "" if r["grb_status"] == "optimal" else "$^*$"
            cells = [r["n"], r["m"], r["H"], r["Z"], f"{float(r['gap_lb_pct']):.1f}" ,
                     f"{pct(r, 'fix_Z_solver'):.1f}", f"{pct(r, 'fix_Z_canonical'):.1f}",
                     f"{pct(r, 'fix_Z_best'):.1f}", f"{float(r['rc_gain_median']):.1f}"]
            body.append(f"{name}{star} & " + " & ".join(g(c) for c in cells) + "\\\\")
    best = [pct(r, "fix_Z_best") for r in ok]
    solver = [pct(r, "fix_Z_solver") for r in ok]
    canon = [pct(r, "fix_Z_canonical") for r in ok]
    gains = [float(r["rc_gain_median"]) for r in ok]
    macros = {
        "litInstances": str(len(ok)),
        "litFempty": str(sum(int(r["F"]) == 0 for r in ok)),
        "litKzeroOne": str(sum(int(r["k0"]) == 1 for r in ok)),
        "litOptimal": str(sum(r["grb_status"] == "optimal" for r in ok)),
        "litZbestMin": str(half_up(min(best))), "litZbestMax": str(half_up(max(best))),
        "litZbestMedian": str(half_up(statistics.median(best))),
        "litZsolverMax": str(half_up(max(solver))), "litZcanonicalMax": str(half_up(max(canon))),
        "litGainMin": str(half_up(min(gains))), "litGainMax": str(half_up(max(gains))),
        "litGainMedian": str(half_up(statistics.median(gains))),
    }
    stamp = ["% generated by experiments/literature_fixing_table.py from " + a.csv + " -- do not edit"]
    stamp += ["% " + h.lstrip("# ") for h in header]
    rows_tex = "\n".join(stamp + body) + "\n"
    macros_tex = "\n".join(stamp + [f"\\newcommand{{\\{k}}}{{\\gen{{{v}}}}}" for k, v in macros.items()]) + "\n"
    if a.rows:
        open(a.rows, "w").write(rows_tex)
    if a.macros:
        open(a.macros, "w").write(macros_tex)
    sys.stdout.write(rows_tex + macros_tex)


if __name__ == "__main__":
    main()
